-- Deals §10 (docs/fub-crm-spec/10-deals-pipelines.md) — DB-backed pipeline/stage
-- config + multi-contact junction + actual close date.
--
-- 1. crm_pipelines / crm_deal_stages (§20.1/§20.2): until now the Kanban's stage
--    columns were a static module (lib/crm/deal-pipelines.ts mirroring the FUB
--    api-export). §9 Manage Pipelines + §10 Add-a-stage require the config to be
--    MUTABLE (owner-only), so it moves into tables, seeded byte-for-byte from
--    docs/fub-crm-spec/api-export/pipelines.json (same ids, names, colors,
--    orderWeights, closedStage flags). crm_deals.pipeline/.stage stay free text
--    matching these names verbatim (the live rows already do).
-- 2. crm_deal_people (§20.4): a deal can carry MULTIPLE contacts (co-buyers,
--    husband+wife sellers) — the single crm_deals.person_id can't. Backfilled
--    from the existing person_id links; person_id is retained as the legacy
--    primary-contact pointer (scope checks still honor it).
-- 3. crm_deals.actual_close_date (§20.10): FUB's model overloads close_date as
--    both projected and actual. The in-house build records the actual close
--    separately; auto-populated when a deal moves into an is_closed_stage stage.
--
-- Access model: service-role only (RLS enabled, no public policies) — same as
-- every other crm_* table. Broker scoping happens in the DAL/actions layer.

create table if not exists public.crm_pipelines (
  id           bigint generated by default as identity primary key,
  name         text not null unique,
  description  text,
  order_weight integer not null default 1000,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.crm_deal_stages (
  id              bigint generated by default as identity primary key,
  pipeline_id     bigint not null references public.crm_pipelines(id) on delete cascade,
  name            text not null,
  color           text not null default '#819cff',
  order_weight    integer not null default 1000,
  is_closed_stage boolean not null default false,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (pipeline_id, name)
);

