-- §20.4 multi-contact junction.
create table if not exists public.crm_deal_people (
  id         bigint generated by default as identity primary key,
  deal_id    bigint not null references public.crm_deals(id) on delete cascade,
  person_id  bigint not null references public.crm_people(id) on delete cascade,
  role       text,
  created_at timestamptz not null default now(),
  unique (deal_id, person_id)
);
create index if not exists crm_deal_people_person_idx on public.crm_deal_people (person_id);

-- Backfill: every existing single-contact link becomes a junction row.
insert into public.crm_deal_people (deal_id, person_id)
select d.id, d.person_id
from public.crm_deals d
where d.person_id is not null
  and exists (select 1 from public.crm_people p where p.id = d.person_id)
on conflict (deal_id, person_id) do nothing;

-- §20.10 actual close date (in-house extension beyond the FUB baseline).
alter table public.crm_deals add column if not exists actual_close_date date;

-- Backfill: deals already sitting in a closed stage adopt their close_date.
update public.crm_deals d
set actual_close_date = d.close_date
from public.crm_deal_stages s
join public.crm_pipelines p on p.id = s.pipeline_id
where d.actual_close_date is null
  and d.close_date is not null
  and s.is_closed_stage = true
  and d.pipeline = p.name
  and d.stage = s.name;

alter table public.crm_pipelines enable row level security;
alter table public.crm_deal_stages enable row level security;
alter table public.crm_deal_people enable row level security;

