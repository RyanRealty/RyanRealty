-- Sarah conversational consent log + funnel stages on the visitor session.
-- 5-year retain on consent. Service-role writes only.

create table if not exists public.sarah_consent_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  retain_until timestamptz not null,
  channel text not null,
  outcome text not null,
  marketing boolean not null default false,
  question text not null,
  reply text not null default '',
  wording_version text not null,
  phone text,
  email text,
  page_url text,
  ip text,
  user_agent text,
  session_id text,
  person_id bigint,
  source text not null default 'sarah-chat'
);

create index if not exists sarah_consent_events_session_idx
  on public.sarah_consent_events (session_id, occurred_at desc);
create index if not exists sarah_consent_events_person_idx
  on public.sarah_consent_events (person_id, occurred_at desc);

comment on table public.sarah_consent_events is
  'Sarah TCPA consent and opt-out log. Retain 5 years. Do not delete before retain_until.';

create table if not exists public.sarah_funnel_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  session_id text not null,
  stage text not null check (stage in ('opened', 'intent', 'name', 'contact', 'consent')),
  intent text,
  person_id bigint,
  page_url text,
  payload jsonb not null default '{}'::jsonb
);

create index if not exists sarah_funnel_events_session_idx
  on public.sarah_funnel_events (session_id, occurred_at desc);

comment on table public.sarah_funnel_events is
  'Sarah lead-funnel stages on the visitor CRM session (opened, intent, name, contact, consent).';

alter table public.sarah_consent_events enable row level security;
alter table public.sarah_funnel_events enable row level security;

create or replace function public.sarah_consent_block_early_delete()
returns trigger
language plpgsql
as $$
begin
  if old.retain_until > now() then
    raise exception 'sarah_consent_events retain_until % has not passed', old.retain_until;
  end if;
  return old;
end;
$$;

drop trigger if exists sarah_consent_block_early_delete on public.sarah_consent_events;
create trigger sarah_consent_block_early_delete
  before delete on public.sarah_consent_events
  for each row
  execute function public.sarah_consent_block_early_delete();
