/**
 * lib/content/process/rules.ts - the one rules file (docs/plans/CONTENT_PROCESS.md,
 * "Rules live in one file, each with an ID").
 *
 * Every rule the content process holds: the ones the factory already enforces
 * (each with the step that first refuses it, the function that refuses, and a
 * fixture that breaks it, proved by rules.test.ts) and the ones CONTENT_PROCESS.md
 * names that nothing enforces yet (status "planned", with the build-order step that
 * will). A rule without an ID, an enforcer or a fixture fails the build
 * (scripts/check-content-rules.mjs, ci:content-rules). `npm run studio -- rules
 * <deliverable-or-video-type>` prints the rules that apply, so instruction files
 * point here instead of restating numbers.
 *
 * Seeded 2026-10-14 from lib/studio/qa/{evaluate,copy-rules,techniques,ledger,
 * measure,check}.ts, lib/studio/timeline/{preflight,plan,voice}.ts and
 * video_gate.mjs. Where a document and the code disagree, the rule records the
 * code's behaviour (see the title); IDs are issued once and never reused.
 *
 * Plain TypeScript with no imports: scripts/check-content-rules.mjs imports this
 * file through tsx (CI runs it on Node 20), so keep it free of imports and of
 * syntax that needs a build step beyond type erasure.
 */

export type DeliverableType = 'video' | 'still' | 'carousel' | 'post_copy' | 'paid_ad'
export type StepId = 'brief' | 'voice' | 'stills' | 'board' | 'animatic' | 'motion' | 'master' | 'certify' | 'approve'

export type RuleThreshold = { source: 'qa' | 'video_types'; path: string; tighterIs: 'lower' | 'higher' }

export type Rule = {
  /** 'R-001'. Stable: never reused, never renumbered. A retired rule keeps its ID. */
  id: string
  /** Plain words, one line. */
  title: string
  /** Where the rule comes from: 'Matt 2026-10-14', 'CLAUDE.md §0', 'RULEBOOK 2b', 'VIDEO_TYPES core 10'. */
  source: string
  appliesTo: readonly DeliverableType[]
  /** When only some video types: listing, market_update, buyer_ad, ... */
  videoTypes?: readonly string[]
  /** The EARLIEST step that enforces it. */
  step: StepId
  /** The video:check check number, when the rule maps to one. */
  check?: number
  status: 'enforced' | 'planned' | 'retired'
  /** Required when enforced: the function that refuses. */
  enforcer?: { module: string; export: string }
  /**
   * When the rule holds a number: where it lives and which way is tighter. An
   * array when one refusal holds two (the safe area has a right edge and a bottom).
   */
  threshold?: RuleThreshold | readonly RuleThreshold[]
  /** Required when enforced: a JSON fixture under lib/content/process/fixtures/ that breaks this rule and nothing else it can avoid. */
  fixture?: string
  /** Required when enforced: a regex (source text) the refusal message must match. */
  fixtureMatch?: string
  /** Required when planned: the build-order step that will enforce it ('process core', 'certifier', 'doors', 'judge', 'library'). */
  plannedIn?: string
}

