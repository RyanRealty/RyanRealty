#!/usr/bin/env node
/**
 * check-search-field-completeness.mjs — ci:search-field-completeness.
 * SEARCH_FILTER_COMPLETENESS_PLAN_2026-07-30 §11.2 + §12 (P5 ratchet).
 *
 * The decision: filter-surface completeness only moves TOWARD exposure. The
 * registry-report's long-tail counts (exposable metadata concepts with no
 * registry mapping) may only shrink, and the exposed-field count may only
 * grow. Without this, the 113-of-239 gap the plan measured silently reopens
 * one convenience-deletion at a time.
 *
 * FAILS on:
 *   (a) REGRESSION — summary.registryFields fell below the committed baseline,
 *       or a long-tail count rose above it (a mapped concept was un-mapped).
 *   (b) UNCOVERED MV COLUMN — a listing_search_mv column (per the committed
 *       schema snapshot) that is neither some registry field's `mv` target,
 *       nor on the curation mask-dead exclusion list, nor in this gate's own
 *       exclusion file with a written reason. Every column a buyer could shop
 *       by is exposed or explicitly excluded — no silent third state.
 *   (c) STALE EXCLUSION — an exclusion entry naming a column that no longer
 *       exists in the MV snapshot, or that a registry field now exposes (the
 *       exclusion must be deleted so the ledger stays honest).
 *
 * Improvements (more fields, smaller long tail) PASS with a notice: run
 * `node scripts/check-search-field-completeness.mjs --update` to ratchet the
 * baseline forward and lock them in.
 *
 * Inputs (ALL static, committed — no network, no DB, no secrets):
 *   - data/search-metadata/registry-report.json   (regenerated by G61's generator)
 *   - data/search-metadata/curation.json          (mask-dead mvColumns)
 *   - docs/DATABASE_SCHEMA_SNAPSHOT.md            (listing_search_mv columns)
 *   - lib/search/field-registry.ts                (mv targets, via the shared AST extractor)
 *   - scripts/search-completeness-baseline.json   (the ratchet + column exclusions)
 *
 * Exit: 0 = no regression, every MV column accounted for. 1 = otherwise.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { extractRegistryFields, loadCuration, REPORT_PATH } from './generate-search-registry.mjs'

const BASELINE_PATH = 'scripts/search-completeness-baseline.json'
const SNAPSHOT_MD = 'docs/DATABASE_SCHEMA_SNAPSHOT.md'
const MV_NAME = 'listing_search_mv'

const root = process.cwd()
const update = process.argv.includes('--update')
const problems = []
const notices = []

// ── Inputs ──────────────────────────────────────────────────────────────────
for (const p of [REPORT_PATH, 'data/search-metadata/curation.json', SNAPSHOT_MD, BASELINE_PATH]) {
  if (!existsSync(join(root, p))) {
    console.error(`✗ ci:search-field-completeness: missing ${p}`)
    process.exit(1)
  }
}

const report = JSON.parse(readFileSync(join(root, REPORT_PATH), 'utf8'))
const curation = loadCuration(root)
const baseline = JSON.parse(readFileSync(join(root, BASELINE_PATH), 'utf8'))
const registryFields = extractRegistryFields(root)

const current = {
  exposedFields: report.summary?.registryFields ?? 0,
  standardLongTail: report.summary?.longTailStandardCount ?? Number.MAX_SAFE_INTEGER,
  customLongTail: report.summary?.longTailCustomCount ?? Number.MAX_SAFE_INTEGER,
}

// ── (a) The ratchet ─────────────────────────────────────────────────────────
if (current.exposedFields < baseline.exposedFields) {
  problems.push(
    `regression: exposed registry fields fell ${baseline.exposedFields} -> ${current.exposedFields}. ` +
      'Removing a filter requires a curation exclusion with a reason AND a deliberate baseline update (--update).',
  )
}
if (current.standardLongTail > baseline.standardLongTail) {
  problems.push(
    `regression: standard long-tail (searchable+IDX, unregistered) rose ${baseline.standardLongTail} -> ${current.standardLongTail}. ` +
      'A previously mapped concept lost its registry mapping.',
  )
}
if (current.customLongTail > baseline.customLongTail) {
  problems.push(
    `regression: custom/group long-tail (searchable, unregistered) rose ${baseline.customLongTail} -> ${current.customLongTail}. ` +
      'A previously mapped concept lost its registry mapping.',
  )
}
const improved =
  current.exposedFields > baseline.exposedFields ||
  current.standardLongTail < baseline.standardLongTail ||
  current.customLongTail < baseline.customLongTail
if (improved && !update) {
  notices.push(
    `improvement not yet locked: ${JSON.stringify(current)} vs baseline ${JSON.stringify({
      exposedFields: baseline.exposedFields,
      standardLongTail: baseline.standardLongTail,
      customLongTail: baseline.customLongTail,
    })} — run with --update to ratchet the baseline.`,
  )
}

// ── (b) MV column coverage ──────────────────────────────────────────────────
// Parse the committed schema snapshot's listing_search_mv section: markdown
// table rows of the form  | `column` | type | ... |
function mvColumnsFromSnapshot() {
  const md = readFileSync(join(root, SNAPSHOT_MD), 'utf8')
  const lines = md.split('\n')
  const start = lines.findIndex((l) => l.trim() === `### \`${MV_NAME}\``)
  if (start === -1) return null
  const cols = []
  for (let i = start + 1; i < lines.length; i += 1) {
    const line = lines[i]
    if (line.startsWith('### ')) break
    const m = line.match(/^\|\s*`([a-z0-9_]+)`\s*\|/)
    if (m) cols.push(m[1])
  }
  return cols
}

const mvColumns = mvColumnsFromSnapshot()
if (!mvColumns || mvColumns.length === 0) {
  problems.push(`cannot parse ${SNAPSHOT_MD} section '### \`${MV_NAME}\`' — snapshot format changed?`)
}

const exposedMvs = new Set(registryFields.map((f) => f.mv).filter(Boolean))
const maskDeadMvs = new Set(
  Object.values(curation.exclusions ?? {}).flatMap((e) => e.mvColumns ?? []),
)
const gateExclusions = baseline.mvColumnExclusions ?? {}

for (const col of mvColumns ?? []) {
  const excludedHere = Object.prototype.hasOwnProperty.call(gateExclusions, col)
  if (exposedMvs.has(col)) {
    if (excludedHere) {
      problems.push(
        `stale exclusion: MV column '${col}' is excluded in ${BASELINE_PATH} but a registry field now exposes it — delete the exclusion entry.`,
      )
    }
    continue
  }
  if (maskDeadMvs.has(col)) continue
  if (excludedHere) {
    const reason = gateExclusions[col]
    if (typeof reason !== 'string' || reason.trim().length < 10) {
      problems.push(`exclusion without a real reason: MV column '${col}' in ${BASELINE_PATH}`)
    }
    continue
  }
  problems.push(
    `uncovered MV column: listing_search_mv.'${col}' is not exposed by any registry field, not on the curation mask-dead list, ` +
      `and not excluded with a reason in ${BASELINE_PATH}. Expose it or write down why not.`,
  )
}

// (c) exclusions naming columns that left the MV
if (mvColumns) {
  const colSet = new Set(mvColumns)
  for (const col of Object.keys(gateExclusions)) {
    if (!colSet.has(col)) {
      problems.push(
        `stale exclusion: '${col}' in ${BASELINE_PATH} no longer exists in the ${MV_NAME} snapshot — delete the entry.`,
      )
    }
  }
}

// ── --update: ratchet the baseline forward (exclusions are hand-owned) ──────
if (update && problems.length === 0) {
  const next = { ...baseline, ...current }
  writeFileSync(join(root, BASELINE_PATH), JSON.stringify(next, null, 2) + '\n')
  console.log(`baseline ratcheted: ${JSON.stringify(current)} -> ${BASELINE_PATH}`)
}

// ── Report ──────────────────────────────────────────────────────────────────
console.log('Search field completeness ratchet (ci:search-field-completeness)')
console.log('================================================================')
console.log(
  `exposed fields: ${current.exposedFields} (baseline ${baseline.exposedFields}) · ` +
    `long tail standard+IDX: ${current.standardLongTail} (≤ ${baseline.standardLongTail}) · ` +
    `custom/group: ${current.customLongTail} (≤ ${baseline.customLongTail}) · ` +
    `MV columns: ${mvColumns?.length ?? '?'} (excluded here: ${Object.keys(gateExclusions).length}, mask-dead: ${maskDeadMvs.size})`,
)
for (const n of notices) console.log(`  ~ ${n}`)
if (problems.length) {
  console.error('\nProblems:')
  for (const p of problems) console.error(`  ✗ ${p}`)
  console.error(
    `\n\x1b[31m✗ ci:search-field-completeness: ${problems.length} problem(s). ` +
      `Completeness only moves toward exposure; every MV column is exposed or excluded with a reason.\x1b[0m`,
  )
  process.exit(1)
}
console.log('✓ no regression; every listing_search_mv column exposed or excluded with a reason.')
process.exit(0)
