#!/usr/bin/env node
/**
 * Forward the Ordway transaction-summary PDF to the SkySlope folder
 * mailbox, then PATCH + checklist-assign to Broker Notes.
 */
import { google } from 'googleapis'
import fs from 'node:fs/promises'
import crypto from 'node:crypto'
import { skyslopeFetchWithRetry } from './skyslope-files-api.mjs'

const FROM = 'matt@ryan-realty.com'
const TO = 'OrdwayAvenue2732@skyslope.com'
const FOLDER = 'f88642ff-22e6-4618-b9e1-40b168a439e1'
const PDF_PATH = `tmp/skyslope-pdfs/${FOLDER}/gap-pulls/transaction-summary.pdf`
const BROKER_NOTES_ACTIVITY = 1050931924
const TARGET_FILENAME = 'MR05072025_X_Broker Notes - Transaction Summary.pdf'
const BASE = 'https://api-latest.skyslope.com'

const auth = new google.auth.JWT({
  email: process.env.GOOGLE_SERVICE_ACCOUNT_CLIENT_EMAIL.trim(),
  key: process.env.GOOGLE_SERVICE_ACCOUNT_PRIVATE_KEY.trim().replace(/\\n/g, '\n'),
  scopes: ['https://www.googleapis.com/auth/gmail.send'],
  subject: FROM,
})
await auth.authorize()
const gmail = google.gmail({ version: 'v1', auth })

const bin = await fs.readFile(PDF_PATH)
const b64 = bin.toString('base64')
const wrapped = b64.match(/.{1,76}/g).join('\r\n')
const boundary = `----rr-broker-notes-${Date.now()}`
const subject = '[Ordway forward] Broker Notes - Transaction Summary - 2732 NW Ordway'
const body =
  'Forwarding the consolidated Broker Notes / Transaction Summary for 2732 NW Ordway (escrow WT0274211, closed 6/9/25 at $880K).\n\n' +
  'This 6-page audit captures: full chronology, all parties (Ryan + Ashlee Bellinson / Stephen Graham + Nicola Anne Murray), 3 sale agreement numbers tracked, escrow + title officer info, form inventory by category, compliance flags resolved, cross-reference table for sale#-less docs.\n\n' +
  'Auto-generated by Ryan Realty SkySlope form-compliance audit pass 2026-05-21.'

const message = [
  `From: ${FROM}`,
  `To: ${TO}`,
  `Subject: ${subject}`,
  'MIME-Version: 1.0',
  `Content-Type: multipart/mixed; boundary="${boundary}"`,
  '',
  `--${boundary}`,
  'Content-Type: text/plain; charset=utf-8',
  'Content-Transfer-Encoding: 7bit',
  '',
  body,
  '',
  `--${boundary}`,
  `Content-Type: application/pdf; name="Broker Notes - Transaction Summary.pdf"`,
  `Content-Disposition: attachment; filename="Broker Notes - Transaction Summary.pdf"`,
  'Content-Transfer-Encoding: base64',
  '',
  wrapped,
  '',
  `--${boundary}--`,
].join('\r\n')

const raw = Buffer.from(message).toString('base64url')
const sendRes = await gmail.users.messages.send({ userId: 'me', requestBody: { raw } })
console.log('Email sent. gmail msgId:', sendRes.data.id)

// Wait + poll for ingest
async function login() {
  const ts = new Date().toISOString()
  const env = process.env
  const hmac = crypto
    .createHmac('sha256', env.SKYSLOPE_ACCESS_SECRET.trim())
    .update(`${env.SKYSLOPE_CLIENT_ID.trim()}:${env.SKYSLOPE_CLIENT_SECRET.trim()}:${ts}`)
    .digest('base64')
  const r = await skyslopeFetchWithRetry(`${BASE}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `ss ${env.SKYSLOPE_ACCESS_KEY.trim()}:${hmac}`, Timestamp: ts },
    body: JSON.stringify({ ClientId: env.SKYSLOPE_CLIENT_ID.trim(), ClientSecret: env.SKYSLOPE_CLIENT_SECRET.trim() }),
  })
  return (await r.json()).Session
}
function apiHeaders(s) {
  return { 'Content-Type': 'application/json', Session: s, timestamp: new Date().toISOString(), Accept: 'application/json' }
}

const session = await login()

async function listDocs() {
  const r = await skyslopeFetchWithRetry(`${BASE}/api/files/sales/${FOLDER}/documents`, { headers: apiHeaders(session) })
  return (await r.json())?.value?.documents || []
}

let newDoc = null
for (let attempt = 0; attempt < 30; attempt++) {
  await new Promise((r) => setTimeout(r, 6000))
  const docs = await listDocs()
  newDoc = docs.find((d) => d.fileName && /Broker.Notes|Transaction.Summary|Broker_Notes|Transaction_Summary/i.test(d.fileName))
  if (newDoc) {
    console.log(`[ingest] found after ${(attempt + 1) * 6}s: ${newDoc.fileName} (docId ${newDoc.docId.slice(0, 8)})`)
    break
  }
  process.stderr.write(`[ingest] poll ${attempt + 1} — not yet\n`)
}
if (!newDoc) {
  console.error('FAIL: doc never ingested')
  process.exit(1)
}

// PATCH rename
const patchRes = await skyslopeFetchWithRetry(
  `${BASE}/api/files/sales/${FOLDER}/documents/${newDoc.docId}`,
  { method: 'PATCH', headers: apiHeaders(session), body: JSON.stringify({ FileName: TARGET_FILENAME }) }
)
console.log(`[patch] status ${patchRes.status} -> ${TARGET_FILENAME}`)

// Assign to Broker Notes activity
const assignRes = await skyslopeFetchWithRetry(
  `${BASE}/api/files/sales/${FOLDER}/checklist-items/${BROKER_NOTES_ACTIVITY}`,
  { method: 'POST', headers: apiHeaders(session), body: JSON.stringify({ documentGuid: newDoc.docId }) }
)
console.log(`[assign] status ${assignRes.status} -> Broker Notes (activityId ${BROKER_NOTES_ACTIVITY})`)
