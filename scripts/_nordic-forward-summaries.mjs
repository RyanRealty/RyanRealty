#!/usr/bin/env node
/**
 * Phase 11a: Forward Nordic transaction-summary PDFs to each folder's SkySlope mailbox.
 *
 * After ingest (typically <60s), the doc lands in the folder. Phase 11b
 * (a separate step) PATCHes the v5 name + POSTs to the Broker Notes activity.
 */
import { google } from 'googleapis'
import fs from 'node:fs/promises'
import path from 'node:path'

const FROM = 'matt@ryan-realty.com'

const FORWARDS = [
  { folder: 'ce3c30de-1b10-4946-bf06-6dbad8e1d53d', label: 'Closed', to: 'NWNordicAvenue26801@skyslope.com' },
  { folder: '6be4810f-eda4-433d-ad6f-f27b80a1c6e0', label: 'Canceled-A', to: 'NWNordicAvenue2680@skyslope.com' },
  { folder: '0ec95d31-1fed-4519-a114-e967513eac33', label: 'Canceled-B', to: null /* no portalEmail */ },
]

const SUBJECT_BASE = '[Nordic Avenue 2680 forward] Broker Notes - Transaction Summary (v5 audit)'
const BODY_BASE = `Transaction summary PDF for 2680 NW Nordic Avenue. Generated by the
skyslope-form-compliance skill after the v5 rename + checklist assignment
pass on 2026-05-22. Includes property + escrow info, parties, sale#s,
form inventory, archive breakdown, checklist state, and outstanding gap
list.

This doc fills the Broker Notes checklist activity.`

async function send(gmail, from, to, subject, body, attachmentPath) {
  const filename = path.basename(attachmentPath)
  const bin = await fs.readFile(attachmentPath)
  const b64 = bin.toString('base64')
  const wrapped = b64.match(/.{1,76}/g).join('\r\n')
  const boundary = `----rr-fwd-${Date.now()}-${Math.random().toString(36).slice(2, 10)}`
  const message = [
    `From: ${from}`,
    `To: ${to}`,
    `Subject: ${subject}`,
    'MIME-Version: 1.0',
    `Content-Type: multipart/mixed; boundary="${boundary}"`,
    '',
    `--${boundary}`,
    'Content-Type: text/plain; charset=utf-8',
    'Content-Transfer-Encoding: 7bit',
    '',
    body,
    '',
    `--${boundary}`,
    `Content-Type: application/pdf; name="${filename}"`,
    `Content-Disposition: attachment; filename="${filename}"`,
    'Content-Transfer-Encoding: base64',
    '',
    wrapped,
    '',
    `--${boundary}--`,
    '',
  ].join('\r\n')
  const raw = Buffer.from(message).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
  const res = await gmail.users.messages.send({ userId: 'me', requestBody: { raw } })
  return res.data
}

const auth = new google.auth.JWT({
  email: process.env.GOOGLE_SERVICE_ACCOUNT_CLIENT_EMAIL.trim(),
  key: process.env.GOOGLE_SERVICE_ACCOUNT_PRIVATE_KEY.trim().replace(/\\n/g, '\n'),
  scopes: ['https://www.googleapis.com/auth/gmail.send'],
  subject: FROM,
})
const gmail = google.gmail({ version: 'v1', auth })
await auth.authorize()
console.error(`[auth] OK — sending as ${FROM}`)

const log = []
for (const f of FORWARDS) {
  if (!f.to) {
    console.error(`[skip] ${f.label} (${f.folder.slice(0, 8)}): no portalEmail — manual upload via UI required.`)
    log.push({ folder: f.folder, label: f.label, status: 'skipped', reason: 'no_portal_email' })
    continue
  }
  const pdfPath = `tmp/skyslope-pdfs/${f.folder}/gap-pulls/transaction-summary.pdf`
  console.error(`[send] ${f.label} → ${f.to}`)
  try {
    const result = await send(gmail, FROM, f.to, `${SUBJECT_BASE} [${f.label}]`, BODY_BASE, pdfPath)
    console.error(`       sent (msg id ${result.id})`)
    log.push({ folder: f.folder, label: f.label, status: 'sent', to: f.to, messageId: result.id, threadId: result.threadId })
  } catch (e) {
    console.error(`       ERROR: ${e.message}`)
    log.push({ folder: f.folder, label: f.label, status: 'error', to: f.to, error: e.message })
  }
}

await fs.writeFile('tmp/skyslope-form-compliance-2026-05-23/nordic-forward-log.json', JSON.stringify(log, null, 2))
console.error(`\nLogged to tmp/skyslope-form-compliance-2026-05-23/nordic-forward-log.json`)
console.error(log.filter((x) => x.status === 'sent').length + ' sent')
