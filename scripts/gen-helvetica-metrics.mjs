#!/usr/bin/env node
/**
 * gen-helvetica-metrics.mjs — writes lib/tc/helvetica-metrics.ts, the glyph
 * widths and kerning pdf-lib's Helvetica uses for every character WinAnsi can
 * encode, read from @pdf-lib/standard-fonts (the data the sealer draws with).
 *
 * The browser measures typed text with this table instead of importing
 * @pdf-lib/standard-fonts, which ships all fourteen standard fonts and pako
 * (about 150 KB) into every chunk that measures text. lib/tc/text-areas.test.ts
 * holds the table to the package, so a pdf-lib upgrade that moves a width
 * fails there; rerun this script to refresh it.
 *
 * Usage: node scripts/gen-helvetica-metrics.mjs
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { Encodings, Font, FontNames } from '@pdf-lib/standard-fonts'

const ROOT = resolve(new URL('.', import.meta.url).pathname, '..')
const OUT = resolve(ROOT, 'lib/tc/helvetica-metrics.ts')

const font = Font.load(FontNames.Helvetica)
const winAnsi = Encodings.WinAnsi

const chars = winAnsi.supportedCodePoints
  .slice()
  .sort((a, b) => a - b)
  .map((cp) => String.fromCodePoint(cp))
const glyph = (ch) => winAnsi.encodeUnicodeCodePoint(ch.codePointAt(0)).name
// helveticaWidth's own fallback for a glyph the font has no width for.
const widths = chars.map((ch) => font.getWidthOfGlyph(glyph(ch)) || 250)

const kern = []
for (const left of chars) {
  let rights = ''
  const amounts = []
  for (const right of chars) {
    const k = font.getXAxisKerningForPair(glyph(left), glyph(right))
    if (k) {
      rights += right
      amounts.push(k)
    }
  }
  if (rights) kern.push([left, rights, amounts])
}

// ASCII only: every other character is written as its \u escape.
const esc = (s) => JSON.stringify(s).replace(/[^\x20-\x7e]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)
const body = `/**
 * Generated by scripts/gen-helvetica-metrics.mjs from @pdf-lib/standard-fonts. Do not edit.
 *
 * pdf-lib's Helvetica for every character WinAnsi can encode: its advance
 * width (1/1000 em) and its kerning with the character after it. The sealer
 * draws typed text in this font; lib/tc/text-areas.ts measures with this table
 * so the browser and the sealer wrap a line at the same word.
 */

/** Every character the sealer can draw, in code point order. */
export const HELVETICA_CHARS = ${esc(chars.join(''))}

/** Advance width of each character in HELVETICA_CHARS, same order. */
export const HELVETICA_WIDTHS: readonly number[] = ${JSON.stringify(widths)}

/** Kerning: [left character, the right characters it kerns with, the amount for each]. */
export const HELVETICA_KERN: readonly (readonly [string, string, readonly number[]])[] = [
${kern.map(([l, r, a]) => `  [${esc(l)}, ${esc(r)}, ${JSON.stringify(a)}],`).join('\n')}
]
`
writeFileSync(OUT, body)
console.log(`Wrote ${OUT}: ${chars.length} characters, ${kern.reduce((s, [, r]) => s + [...r].length, 0)} kerning pairs`)
