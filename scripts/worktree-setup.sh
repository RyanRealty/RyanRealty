#!/usr/bin/env sh
# worktree-setup.sh — make a fresh `git worktree add` safe to work and push from.
#
# Three things a new worktree lacks, each of which fails in a different and
# non-obvious way:
#
#   node_modules  — gitignored. Absent, `npx tsc` silently resolves to the bogus
#                   npm package `tsc@2.0.4`, prints nothing and EXITS 0, so a
#                   typecheck that verified nothing looks green. A symlink is
#                   NOT a fix for a production build: Turbopack refuses a
#                   node_modules resolving outside the project root. So the
#                   default is a copy: an APFS clone on macOS (cp -Rc,
#                   copy-on-write, ~30s and almost no real disk), a reflink on a
#                   Linux filesystem that has them, else a plain copy (about 2 GB;
#                   refused up front when the disk cannot hold it).
#                   `--link` makes a symlink instead. That is fine for tsc,
#                   vitest and eslint, and it is the only choice when the disk is
#                   too full to copy, but a `next build` from a linked tree fails.
#
#   .env.local    — gitignored. Absent, the production build dies in static
#                   generation on missing NEXT_PUBLIC_SUPABASE_* vars. Copied
#                   when the main checkout has one; a cloud checkout that takes
#                   its env from the process has none, which is not an error.
#
#   .husky/_      — generated by husky at install time, gitignored. Absent,
#                   core.hooksPath (the RELATIVE path .husky/_) resolves to
#                   nothing, git runs no hooks, and a push skips the entire gate
#                   chain and the production build while still succeeding.
#                   Enforced by scripts/check-hooks-installed.mjs. This step runs
#                   first and unconditionally: a failure further down (a full
#                   disk, a missing .env.local) must never leave a tree with no
#                   hooks.
#
# The main checkout is the FIRST entry of `git worktree list --porcelain`, wherever
# it lives (the old default, $HOME/RyanRealty, was wrong on every machine that
# keeps it elsewhere). Pass a path to override.
#
# usage: sh scripts/worktree-setup.sh [--link] [path-to-main-checkout]

set -e

LINK=0
MAIN=""
for arg in "$@"; do
  case "$arg" in
    --link) LINK=1 ;;
    *) MAIN="$arg" ;;
  esac
done

TOP="$(git rev-parse --show-toplevel)"
if [ -z "$MAIN" ]; then
  MAIN="$(git worktree list --porcelain | sed -n '1s/^worktree //p')"
fi

if [ "$TOP" = "$MAIN" ]; then
  echo "worktree-setup: already in the main checkout, nothing to do."
  exit 0
fi

if [ -z "$MAIN" ] || [ ! -d "$MAIN/.husky/_" ]; then
  echo "worktree-setup: no main checkout with .husky/_ found (looked at: ${MAIN:-nothing}). Pass its path as the argument." >&2
  exit 1
fi

echo "worktree-setup: $TOP  (source: $MAIN)"

# 1. Hooks: first, and never skipped.
if [ ! -f "$TOP/.husky/_/pre-push" ]; then
  echo "  .husky/_: installing hooks"
  mkdir -p "$TOP/.husky"
  cp -R "$MAIN/.husky/_" "$TOP/.husky/_"
else
  echo "  .husky/_: present"
fi

# 2. .env.local, when the main checkout has one.
if [ ! -f "$TOP/.env.local" ]; then
  if [ -f "$MAIN/.env.local" ]; then
    echo "  .env.local: copying"
    cp "$MAIN/.env.local" "$TOP/.env.local"
  else
    echo "  .env.local: none in $MAIN (a build needs NEXT_PUBLIC_SUPABASE_* from the environment)"
  fi
else
  echo "  .env.local: present"
fi

# 3. node_modules.
if [ ! -x "$TOP/node_modules/.bin/tsc" ]; then
  rm -rf "$TOP/node_modules" 2>/dev/null || true
  if [ "$LINK" = 1 ]; then
    echo "  node_modules: symlink to $MAIN/node_modules (typecheck and tests only; next build needs a copy)"
    ln -s "$MAIN/node_modules" "$TOP/node_modules"
  elif [ "$(uname -s)" = "Darwin" ]; then
    echo "  node_modules: APFS clone from $MAIN …"
    cp -Rc "$MAIN/node_modules" "$TOP/node_modules"
  elif cp -R --reflink=always "$MAIN/node_modules" "$TOP/node_modules" 2>/dev/null; then
    echo "  node_modules: reflink copy from $MAIN"
  else
    rm -rf "$TOP/node_modules"
    need="$(du -sk "$MAIN/node_modules" | cut -f1)"
    have="$(df -Pk "$TOP" | awk 'NR==2 { print $4 }')"
    if [ "$have" -lt $((need + need / 10)) ]; then
      echo "worktree-setup: not enough free disk to copy node_modules (${need} KB needed, ${have} KB free)." >&2
      echo "  Free some space, or re-run with --link for a tree that only typechecks and runs tests." >&2
      exit 1
    fi
    echo "  node_modules: full copy from $MAIN …"
    cp -R "$MAIN/node_modules" "$TOP/node_modules"
  fi
else
  echo "  node_modules: present"
fi

echo "worktree-setup: verifying"
node "$TOP/scripts/check-hooks-installed.mjs"
echo "worktree-setup: ready — this tree can typecheck, build, and push gated."
