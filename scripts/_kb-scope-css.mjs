// Port the locked prototype's <style> block into a scoped, Next-safe stylesheet.
// Every rule is namespaced under `.kb-root` so importing it cannot leak into the
// shadcn site. Lenis/html rules stay global (Lenis adds .lenis to <html>).
// @font-face for Amboqia is dropped (we use the next/font var). Asset URLs fixed.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const SRC = '/Users/matthewryan/RyanRealty/out/concept/v2/kinetic-brutalist.html'
const OUT = '/Users/matthewryan/RyanRealty/components/site/kb/kb.css'

const html = readFileSync(SRC, 'utf8')
const m = html.match(/<style>([\s\S]*?)<\/style>/)
if (!m) throw new Error('no <style> block found')
let css = m[1]
// strip @import (Geist is loaded by next/font); url() may contain semicolons
css = css.replace(/@import\s+url\([^)]*\)\s*;/g, '')

// body-level fixups applied to every declaration block
function fixDecls(body) {
  return body
    .replaceAll(/font-family:\s*'Amboqia',\s*serif/g, "font-family:var(--font-amboqia),serif")
    .replaceAll("'Amboqia'", 'var(--font-amboqia)')
    .replaceAll("'Geist'", 'var(--font-sans)')
    .replaceAll('/out/concept/v2/img/', '/images/kb/')
    .replaceAll('/public/images/', '/images/')
}

function prefixOne(s) {
  s = s.trim()
  if (!s) return s
  // keep Lenis + html-level rules global
  if (s.startsWith('html') || s.startsWith('.lenis')) return s
  if (s === 'body') return '.kb-root'
  if (s === ':root') return '.kb-root'
  if (s === '*') return '.kb-root *'
  if (s.startsWith('::')) return '.kb-root ' + s
  return '.kb-root ' + s
}
const prefixSel = (sel) => sel.split(',').map(prefixOne).join(', ')

// walk top-level blocks
let out = []
let i = 0
const n = css.length
function readBlock(start) {
  // returns [selectorOrAt, bodyText, endIndex] where bodyText is inside {}
  let j = start
  while (j < n && css[j] !== '{') j++
  const head = css.slice(start, j).trim()
  // find matching brace
  let depth = 0, k = j
  for (; k < n; k++) {
    if (css[k] === '{') depth++
    else if (css[k] === '}') { depth--; if (depth === 0) break }
  }
  return [head, css.slice(j + 1, k), k + 1]
}

while (i < n) {
  // skip whitespace + comments
  while (i < n && /\s/.test(css[i])) i++
  if (i >= n) break
  if (css.startsWith('/*', i)) { const e = css.indexOf('*/', i); i = e === -1 ? n : e + 2; continue }
  if (css.startsWith('@import', i)) { const e = css.indexOf(';', i); i = e === -1 ? n : e + 1; continue }
  const [head, body, end] = readBlock(i)
  i = end
  if (/^@font-face/i.test(head)) {
    if (/Amboqia/i.test(body)) continue // drop the @font-face, use next/font var
    out.push(`@font-face{${fixDecls(body)}}`)
  } else if (/^@keyframes/i.test(head)) {
    out.push(`${head}{${body}}`) // keyframes bodies are %-rules, leave intact
  } else if (/^@media/i.test(head) || /^@supports/i.test(head)) {
    // prefix the inner rules
    const inner = body
    let parts = []
    let p = 0
    while (p < inner.length) {
      while (p < inner.length && /\s/.test(inner[p])) p++
      if (p >= inner.length) break
      if (inner.startsWith('/*', p)) { const e = inner.indexOf('*/', p); p = e === -1 ? inner.length : e + 2; continue }
      // read inner block
      let q = p
      while (q < inner.length && inner[q] !== '{') q++
      const isel = inner.slice(p, q).trim()
      let depth = 0, r = q
      for (; r < inner.length; r++) { if (inner[r] === '{') depth++; else if (inner[r] === '}') { depth--; if (depth === 0) break } }
      const ibody = inner.slice(q + 1, r)
      p = r + 1
      if (/^@keyframes/i.test(isel)) parts.push(`${isel}{${ibody}}`)
      else parts.push(`${prefixSel(isel)}{${fixDecls(ibody)}}`)
    }
    out.push(`${head}{${parts.join('')}}`)
  } else {
    out.push(`${prefixSel(head)}{${fixDecls(body)}}`)
  }
}

mkdirSync('/Users/matthewryan/RyanRealty/components/site/kb', { recursive: true })
const header = `/* Kinetic-brutalist homepage styles — ported from out/concept/v2/kinetic-brutalist.html\n   Scoped under .kb-root so this cannot leak into the shadcn site. Generated by scripts/_kb-scope-css.mjs. */\n`
writeFileSync(OUT, header + out.join('\n') + '\n')
console.log('wrote', OUT, '(' + (header + out.join('\n')).length + ' bytes,', out.length, 'top-level rules)')
